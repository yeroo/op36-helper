pub fn hid_to_scancode(usage: u8) -> Option<ScanCode> {
    TABLE.iter().find(|(h, _)| *h == usage).map(|(_, s)| *s)
}

pub fn scancode_to_hid(scancode: ScanCode) -> Option<u8> {
    TABLE.iter().find(|(_, s)| *s == scancode).map(|(h, _)| *h)
}

/// `true` for the eight HID modifier usages.
pub fn is_modifier_usage(usage: u8) -> bool {
    (0xE0..=0xE7).contains(&usage)
}

//! HID usage ↔ PS/2 set-1 scan code table (what Windows reports for each physical key).

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ScanCode {
    pub code: u8,
    /// Set when the scan code is prefixed with `E0` (arrows, navigation cluster, right modifiers…).
    pub extended: bool,
}

const fn sc(code: u8) -> ScanCode {
    ScanCode { code, extended: false }
}

const fn ext(code: u8) -> ScanCode {
    ScanCode { code, extended: true }
}

